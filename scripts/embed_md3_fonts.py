#!/usr/bin/env python3
"""Embed the exact OFL Roboto sources used by the MD3 reference captures.

The byte arrays are generated in the build tree, never checked into source.
No font transformation or extra Python dependency is involved.
"""

import argparse
import hashlib
from pathlib import Path


FONTS = (
    ("Roboto-400.ttf", "kRobotoRegular", "ae5676deb6b3e57e2856bead5fbc0905e01eda2398b03af98939938c4dcc112c"),
    ("Roboto-500.ttf", "kRobotoMedium", "98189dadd0e2f265c8ef0fde75e7e320dbb4c0babde3ed1e6baf33ea20c2d910"),
)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    parts = [
        "// Generated by scripts/embed_md3_fonts.py. Do not edit.",
        "// Roboto is licensed under OFL-1.1; see tests/md3_web/fonts/OFL.txt.",
        "#pragma once",
        "namespace aimgui::md3_font_data {",
    ]
    for filename, symbol, expected in FONTS:
        data = (args.font_dir / filename).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if digest != expected:
            raise SystemExit(f"{filename}: SHA-256 mismatch; expected pinned reference font {expected}, got {digest}")
        parts.append(f"// {filename}: SHA-256 {digest}")
        parts.append(f"alignas(4) inline constexpr unsigned char {symbol}[] = {{")
        for offset in range(0, len(data), 16):
            parts.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 16]) + ",")
        parts.append("};")
    parts.append("} // namespace aimgui::md3_font_data\n")
    contents = "\n".join(parts)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text(encoding="utf-8") != contents:
        args.output.write_text(contents, encoding="utf-8")


if __name__ == "__main__":
    main()
