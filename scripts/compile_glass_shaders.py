#!/usr/bin/env python3
"""Generate matching Vulkan SPIR-V and GLES strings from shared glass sources."""
import argparse
import os
import shutil
import struct
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT/'jni/src/core/shaders'

def gles_header():
    common = (SRC/'glass_common.glsl').read_text()
    lines = ['// Generated by scripts/compile_glass_shaders.py; do not edit.',
             '#pragma once', 'namespace aimgui::glass_gl_sources {']
    for name, filename in [('kVS', 'glass_gl.vert'), ('kFS', 'glass_gl.frag')]:
        source = (SRC/filename).read_text().replace('#include "glass_common.glsl"', common)
        lines.append(f'inline constexpr char {name}[] = R"GLSL({source})GLSL";')
    return '\n'.join(lines) + '\n}\n'

def vulkan_header(glslc):
    lines = ['// Generated by scripts/compile_glass_shaders.py; do not edit.',
             '#pragma once', '#include <cstdint>', 'namespace aimgui::glass_vk_spv {']
    with tempfile.TemporaryDirectory() as tmp:
        for name, stage in [('kVS', 'vert'), ('kFS', 'frag')]:
            output = Path(tmp)/(stage+'.spv')
            subprocess.run([glslc, '--target-env=vulkan1.0', '-O', str(SRC/('glass.'+stage)), '-o', str(output)], check=True)
            validator = shutil.which('spirv-val')
            if validator:
                subprocess.run([validator, '--target-env', 'vulkan1.0', str(output)], check=True)
            data = output.read_bytes()
            words = struct.unpack('<%dI' % (len(data)//4), data)
            lines.append(f'inline constexpr uint32_t {name}[] = {{')
            for start in range(0, len(words), 8):
                lines.append('    '+' '.join(f'0x{w:08x},' for w in words[start:start+8]))
            lines.append('};')
    return '\n'.join(lines) + '\n}\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--glslc', default=os.environ.get('GLSLC'))
    args = parser.parse_args()
    compiler = args.glslc or shutil.which('glslc')
    if not compiler:
        ndk = os.environ.get('ANDROID_NDK_HOME', os.environ.get('NDK_ROOT', ''))
        matches = list((Path(ndk)/'shader-tools').glob('*/glslc')) if ndk else []
        compiler = str(matches[0]) if matches else None
    if not compiler:
        parser.error('Set ANDROID_NDK_HOME or GLSLC, or install glslc')
    outputs = {'glass_gl_sources.h': gles_header(), 'glass_vk_spv.h': vulkan_header(compiler)}
    for filename, content in outputs.items():
        path = ROOT/'jni/src/core'/filename
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'{filename} is stale; regenerate with Android NDK r29')
        else:
            path.write_text(content)
    print('Glass shaders: ' + ('verified' if args.check else 'generated'))
