#!/usr/bin/env python3
"""Reproduce the native MaterialShapes catalogue using AndroidX's JVM geometry.

Requires Python 3 and Java 17+. Dependencies are downloaded once, SHA-256 verified,
and cached in build/material-shapes-export. No JVM is needed by the C++ library.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import urllib.request


ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
DATA = ROOT / "third_party/material_shapes"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def cpp_float(value):
    # Kotlin Float.toString() is shortest-round-trip; Python's 9 significant
    # digits also round-trip every binary32 value into a C++ float literal.
    result = format(value, ".9g")
    if "." not in result and "e" not in result:
        result += ".0"
    return result + "f"


def cpp_data(shapes):
    text = [
        "// Generated by scripts/material_shapes/export.py; do not edit.",
        "// Copyright 2024 The Android Open Source Project",
        "// SPDX-License-Identifier: Apache-2.0",
        "// See third_party/material_shapes/{LICENSE,NOTICE,provenance.json}.",
        "",
    ]
    for shape in shapes:
        name = shape["name"]
        text.append(f"static const ShapeCubic k{name}Cubics[] = {{")
        for cubic in shape["cubics"]:
            pairs = ["{" + cpp_float(cubic[i]) + ", " + cpp_float(cubic[i + 1]) + "}"
                     for i in range(0, 8, 2)]
            text.append("    {" + ", ".join(pairs) + "},")
        text.extend(["};", ""])
    text.append("static const ShapeGeometry kShapeGeometries[] = {")
    for shape in shapes:
        name, center = shape["name"], shape["center"]
        text.append(f'    {{"{name}", k{name}Cubics, {len(shape["cubics"])}, '
                    f'{{{cpp_float(center[0])}, {cpp_float(center[1])}}}}},')
    text.extend(["};", ""])
    return "\n".join(text).encode()


def generate_source():
    original = (DATA / "upstream/MaterialShapes.kt").read_text()
    names = re.findall(r"public val (\w+): RoundedPolygon", original)
    assert len(names) == 35, "Review the exporter if upstream's catalogue changes"
    # Preserve the class body verbatim. Its polygon construction, rounding,
    # mirroring, transformations and normalized() calls are all upstream code.
    body = original[original.index("public sealed class MaterialShapes"):]
    pairs = ",\n".join(f'        "{name}" to MaterialShapes.{name}' for name in names)
    main = r'''
fun main() {
    val shapes = listOf(
__PAIRS__)
    println("[")
    shapes.forEachIndexed { index, (name, p) ->
        val bounds = p.calculateBounds(approximate = false)
        print("{\"name\":\"$name\",\"center\":[${p.centerX},${p.centerY}],\"bounds\":[${bounds.joinToString()}],\"cubics\":[")
        p.cubics.forEachIndexed { i, c ->
            if (i > 0) print(",")
            print("[${c.anchor0X},${c.anchor0Y},${c.control0X},${c.control0Y},${c.control1X},${c.control1Y},${c.anchor1X},${c.anchor1Y}]")
        }
        println("]}" + if (index + 1 < shapes.size) "," else "")
    }
    println("]")
}
'''.replace("__PAIRS__", pairs)
    return (HERE / "Adapter.kt").read_text() + body + main


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="regenerate and compare without changing tracked outputs")
    parser.add_argument("--cache", type=Path, default=ROOT / "build/material-shapes-export")
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    provenance = json.loads((DATA / "provenance.json").read_text())
    for source in provenance["sources"]:
        path = DATA / source["path"]
        if digest(path) != source["sha256"]:
            raise SystemExit(f"Pinned source hash mismatch: {path}")

    dependencies = json.loads((HERE / "dependencies.lock.json").read_text())
    for dependency in dependencies:
        path = args.cache / dependency["file"]
        if not path.exists():
            print(f'Downloading {dependency["file"]}', flush=True)
            with urllib.request.urlopen(dependency["url"], timeout=60) as response:
                payload = response.read()
            if hashlib.sha256(payload).hexdigest() != dependency["sha256"]:
                raise SystemExit(f"Dependency hash mismatch: {dependency['file']}")
            path.write_bytes(payload)
        elif digest(path) != dependency["sha256"]:
            raise SystemExit(f"Cached dependency hash mismatch: {path}")

    jar_classpath = os.pathsep.join(str(args.cache / d["file"]) for d in dependencies)
    with tempfile.TemporaryDirectory(prefix="material-shapes-", dir=args.cache) as temp:
        work = Path(temp)
        source = work / "Export.kt"
        source.write_text(generate_source())
        target = work / "export.jar"
        subprocess.run([
            "java", "-cp", jar_classpath, "org.jetbrains.kotlin.cli.jvm.K2JVMCompiler",
            "-no-stdlib", "-no-reflect", "-jvm-target", "17", "-classpath", jar_classpath,
            "-d", str(target), str(source),
        ], check=True)
        raw = subprocess.check_output(["java", "-cp", str(target) + os.pathsep + jar_classpath, "ExportKt"])
    shapes = json.loads(raw)
    outputs = {"material_shapes.json": raw, "material_shapes_data.inc": cpp_data(shapes)}
    for name, contents in outputs.items():
        path = DATA / name
        if args.check:
            if not path.exists() or path.read_bytes() != contents:
                raise SystemExit(f"Generated output differs: {path}")
        else:
            path.write_bytes(contents)
    print(f'{"Verified" if args.check else "Exported"} {len(shapes)} shapes / '
          f'{sum(len(s["cubics"]) for s in shapes)} cubics')


if __name__ == "__main__":
    main()
